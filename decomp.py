#!/usr/bin/env python3
"""
Tiny Toon Adventures GB decompressor/recompressor.

SUPPORTED FORMS

Extract:
    decomp.py -extract tinytoon.gb 0x12345 output.bin
    decomp.py tinytoon.gb 0x12345 output.bin
    decomp.py -extract tinytoon.gb 0x12345 output.bin --size 0x800

Inject:
    decomp.py -inject output.bin tinytoon.gb 0x12345
    decomp.py output.bin tinytoon.gb 0x12345 -inject

The no-command extract form is supported specifically so a ROM filename
cannot be mistaken for an argparse subcommand.

The decompressed extraction size is customizable with --size.
Injection automatically uses the exact size of the decompressed input file.
"""

import argparse
import sys
from pathlib import Path

DEFAULT_OUTPUT_SIZE = 0x6C0
WINDOW_SIZE = 0x400
INITIAL_BYTE = 0x20
INITIAL_WINBC = 0x3DE
MIN_MATCH = 3
MAX_MATCH = 34


def number(s):
    s = str(s).strip()
    try:
        return int(s, 16) if s.lower().startswith("0x") else int(s, 0)
    except ValueError:
        try:
            return int(s, 16)
        except ValueError:
            raise argparse.ArgumentTypeError(f"invalid number: {s}")


def decompress(data, offset, size):
    if not 0 <= offset < len(data):
        raise ValueError("offset is outside the ROM")
    if size <= 0:
        raise ValueError("output size must be greater than zero")

    si = offset
    out = bytearray()
    window = bytearray([INITIAL_BYTE] * WINDOW_SIZE)
    dd28 = 1
    dd29 = 0
    winbc = INITIAL_WINBC

    def nxt():
        nonlocal si
        if si < len(data):
            b = data[si]
            si += 1
            return b
        return 0

    def emit(a):
        nonlocal winbc
        out.append(a)
        window[winbc & 0x3FF] = a
        winbc = (winbc + 1) & 0x3FF

    while len(out) < size:
        dd28 -= 1
        if dd28 == 0:
            dd28 = 8
            dd29 = nxt()

        c = dd29 & 1
        dd29 = ((dd29 >> 1) | ((dd29 & 1) << 7)) & 0xFF

        if c:
            emit(nxt())
        else:
            b1 = nxt()
            b2 = nxt()
            length = (b2 & 0x1F) + 3
            de = (b1 | (((b2 >> 5) & 3) << 8)) & 0x3FF

            for _ in range(length):
                if len(out) >= size:
                    break
                emit(window[de])
                de = (de + 1) & 0x3FF

    return bytes(out), si


def compress(raw):
    if not raw:
        raise ValueError("decompressed input is empty")

    window = bytearray([INITIAL_BYTE] * WINDOW_SIZE)
    winbc = INITIAL_WINBC
    tokens = []
    pos = 0

    while pos < len(raw):
        max_len = min(MAX_MATCH, len(raw) - pos)
        best_len = 0
        best_ofs = 0

        for ofs in range(WINDOW_SIZE):
            # The decompressor copies through the ring buffer while also
            # writing each emitted byte back into that same ring. Therefore
            # overlapping matches must be compared against the bytes that
            # would already have been generated by this candidate.
            distance = (winbc - ofs) & 0x3FF

            # A reference to the current write position is not a previously
            # available byte, so do not use distance zero.
            if distance == 0:
                continue

            n = 0
            test = ofs

            while n < max_len:
                if n < distance:
                    value = window[test]
                else:
                    # Overlap: the decompressor would now read a byte that
                    # was emitted earlier by this very match.
                    value = raw[pos + n - distance]

                if value != raw[pos + n]:
                    break

                n += 1
                test = (test + 1) & 0x3FF

            if n >= MIN_MATCH and n > best_len:
                best_len = n
                best_ofs = ofs
                if n == max_len:
                    break

        if best_len >= MIN_MATCH:
            tokens.append((0, best_ofs, best_len))
            for i in range(best_len):
                window[winbc] = raw[pos + i]
                winbc = (winbc + 1) & 0x3FF
            pos += best_len
        else:
            tokens.append((1, raw[pos]))
            window[winbc] = raw[pos]
            winbc = (winbc + 1) & 0x3FF
            pos += 1

    out = bytearray()
    ti = 0

    while ti < len(tokens):
        flag_pos = len(out)
        out.append(0)
        flags = 0

        for bit in range(8):
            if ti >= len(tokens):
                break

            t = tokens[ti]

            if t[0] == 1:
                flags |= 1 << bit
                out.append(t[1])
            else:
                _, ofs, length = t
                out.append(ofs & 0xFF)
                out.append((((ofs >> 8) & 3) << 5) | ((length - 3) & 0x1F))

            ti += 1

        out[flag_pos] = flags

    check, _ = decompress(bytes(out), 0, len(raw))
    if check != raw:
        raise RuntimeError("compression round-trip verification failed")

    return bytes(out)


def do_extract(rom, offset, output, size):
    data = rom.read_bytes()
    raw, end = decompress(data, offset, size)
    output.write_bytes(raw)

    print("EXTRACT OK")
    print(f"ROM:       {rom}")
    print(f"Offset:    0x{offset:X}")
    print(f"Output:    {output}")
    print(f"Size:      0x{len(raw):X} ({len(raw)} bytes)")
    print(f"Used:      0x{end-offset:X} ({end-offset} compressed bytes)")


def do_inject(src, rom, offset, max_size):
    raw = src.read_bytes()
    data = bytearray(rom.read_bytes())

    packed = compress(raw)

    # Find original compressed size using the actual decompressed input size.
    _, old_end = decompress(bytes(data), offset, len(raw))
    old_size = old_end - offset
    reserved = old_size if max_size is None else max_size

    if len(packed) > reserved:
        raise ValueError(
            f"compressed output 0x{len(packed):X} exceeds available "
            f"region 0x{reserved:X}"
        )

    end = offset + len(packed)
    region_end = offset + reserved

    if region_end > len(data):
        raise ValueError("compressed region extends beyond ROM")

    data[offset:end] = packed

    if end < region_end:
        data[end:region_end] = b"\x00" * (region_end - end)

    rom.write_bytes(data)

    verify, used = decompress(rom.read_bytes(), offset, len(raw))
    if verify != raw:
        raise RuntimeError("injection verification failed")

    print("INJECT OK")
    print(f"Input:     {src}")
    print(f"ROM:       {rom}")
    print(f"Offset:    0x{offset:X}")
    print(f"Input:     0x{len(raw):X} ({len(raw)} bytes)")
    print(f"Packed:    0x{len(packed):X} ({len(packed)} bytes)")
    print(f"Old size:  0x{old_size:X} ({old_size} bytes)")
    print(f"Verified:  0x{used-offset:X} ({used-offset} bytes)")


def main():
    argv = sys.argv[1:]

    if not argv:
        print("Usage:")
        print("  decomp.py -extract ROM OFFSET OUTPUT [--size SIZE]")
        print("  decomp.py ROM OFFSET OUTPUT [--size SIZE]")
        print("  decomp.py -inject INPUT ROM OFFSET [--max-size SIZE]")
        return 2

    # IMPORTANT:
    # Do NOT use an argparse subparser. The old version did that and produced:
    #   invalid choice: 'tinytoon.gb'
    #
    # Detect the requested operation ourselves.
    command = None

    if argv[0] == "-extract":
        command = "extract"
        argv = argv[1:]
    elif argv[0] == "-inject":
        command = "inject"
        argv = argv[1:]
    elif len(argv) >= 4 and argv[3] == "-inject":
        command = "inject"
        argv = argv[:3] + argv[4:]
    elif len(argv) >= 3:
        # If no command is supplied, the requested three-argument form is
        # extraction: ROM OFFSET OUTPUT.
        command = "extract"

    parser = argparse.ArgumentParser(description="Tiny Toon GB codec")

    if command == "extract":
        parser.add_argument("rom")
        parser.add_argument("offset", type=number)
        parser.add_argument("output")
        parser.add_argument("--size", type=number, default=DEFAULT_OUTPUT_SIZE)

        args = parser.parse_args(argv)

        try:
            do_extract(
                Path(args.rom),
                args.offset,
                Path(args.output),
                args.size,
            )
        except (OSError, ValueError, RuntimeError) as e:
            print(f"ERROR: {e}", file=sys.stderr)
            return 1

    elif command == "inject":
        parser.add_argument("input")
        parser.add_argument("rom")
        parser.add_argument("offset", type=number)
        parser.add_argument("--max-size", type=number, default=None)

        args = parser.parse_args(argv)

        try:
            do_inject(
                Path(args.input),
                Path(args.rom),
                args.offset,
                args.max_size,
            )
        except (OSError, ValueError, RuntimeError) as e:
            print(f"ERROR: {e}", file=sys.stderr)
            return 1

    else:
        print("ERROR: use -extract or -inject", file=sys.stderr)
        return 2

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
